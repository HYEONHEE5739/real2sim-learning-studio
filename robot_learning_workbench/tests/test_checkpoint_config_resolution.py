def test_resume_rechecks_request_against_frozen_official_config_before_child(tmp_path,training_data,monkeypatch):
    from robot_learning_workbench.learning import train as module
    requested=_ui_config(training_data,tmp_path/'scratch')
    resolved=_official_validate(requested,tmp_path/'input/train_config.json',monkeypatch)
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',resolved)
    record=seal_checkpoint(checkpoint,dataset=training_data,config=requested,recipe_sha256='f'*64)
    record['config']['policy']['dim_model']+=8
    (checkpoint/'workbench-checkpoint.json').write_text(json.dumps(record))
    new=copy.deepcopy(record['config']);new.update(resume=True,steps=4,output_dir=str(tmp_path/'resume'))
    plan=_plan(tmp_path,new,mode='resume',checkpoint=checkpoint)
    def forbidden(*args,**kwargs):raise AssertionError('Invalid request reached optimization process')
    monkeypatch.setattr(module.subprocess,'Popen',forbidden)
    with pytest.raises(native.DataError,match='Frozen checkpoint'):
        module.train(plan,events=lambda _:None,commands=lambda:())
    assert not plan.output_path.exists()
