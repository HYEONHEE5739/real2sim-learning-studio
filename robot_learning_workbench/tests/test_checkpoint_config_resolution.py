def _ui_config(dataset,output):
    cfg=execute({'operation':'training_config','arguments':{
        'policy_type':'act','dataset':str(dataset),'output':str(output)}})['config']
    # Preserve the complete UI JSON including null/default fields. Restrict
    # runtime to CPU and tiny steps; neither optimization nor model init runs.
    cfg['policy']['device']='cpu'
    cfg.update(steps=2,batch_size=1,num_workers=0,save_freq=1,log_freq=1)
    return cfg


def _official_validate(config,path,monkeypatch,*,overrides=()):
    from lerobot.configs.train import TrainPipelineConfig
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(config))
    args=['--config_path='+str(path),*overrides]
    with monkeypatch.context()as context:
        context.setattr(sys,'argv',['lerobot-train',*args])
        resolved=TrainPipelineConfig.from_pretrained(path,local_files_only=True,cli_args=list(overrides))
        resolved.validate()
    return resolved


def _tiny_checkpoint(root,resolved,step=1):
    import torch
    from safetensors.torch import save_file
    from lerobot.utils.train_utils import save_training_state
    policy=root/'pretrained_model';policy.mkdir(parents=True)
    resolved.save_pretrained(policy)
    resolved.policy.save_pretrained(policy)
    save_file({'fixture_only':torch.ones(1)},str(policy/'model.safetensors'))
    for name in ('policy_preprocessor.json','policy_postprocessor.json'):
        (policy/name).write_text(json.dumps({'fixture_only':True}))
    optimizer=resolved.optimizer.build([torch.nn.Parameter(torch.ones(1))])
    scheduler=resolved.scheduler.build(optimizer,resolved.steps)if resolved.scheduler else None
    save_training_state(root,step,optimizer,scheduler)
    return root


def _plan(path,config,*,mode='scratch',checkpoint=None,policy=None):
    cfg_path=path/'request.json';cfg_path.write_text(json.dumps(config))
    inputs={'dataset':config['dataset']['root'],'training_config':str(cfg_path)}
    if checkpoint is not None:inputs['checkpoint']=str(checkpoint)
    if policy is not None:inputs['policy']=str(policy)
    recipe=path/'recipe.yaml'
    recipe.write_text(yaml.safe_dump({'schema_version':1,'stage':'train','inputs':inputs,
        'execution':{'mode':mode},'output':{'directory':config['output_dir']}}))
    return prepare_recipe(read_recipe(recipe))


def test_full_ui_act_defaults_seal_after_official_normalization(tmp_path,training_data,monkeypatch):
    requested=_ui_config(training_data,tmp_path/'run')
    assert requested['job_name']is None and requested['optimizer']is None
    before=copy.deepcopy(requested)
    resolved=_official_validate(requested,tmp_path/'parsed/train_config.json',monkeypatch)
    actual=resolved.to_dict()
    assert actual['job_name']=='act'and actual['optimizer']['type']=='adamw'
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',resolved)
    record=seal_checkpoint(checkpoint,dataset=training_data,config=requested,recipe_sha256='1'*64)
    assert record['complete']is True and record['step']==1
    assert checkpoint_record(checkpoint)['dataset_identity']==vars(native.load_catalog(training_data).identity)
    assert requested==before


def test_full_ui_request_reaches_training_command_and_owned_frozen_resume_seals(tmp_path,training_data,monkeypatch):
    requested=_ui_config(training_data,tmp_path/'scratch')
    scratch_plan=_plan(tmp_path,requested)
    argv,config=training_command(scratch_plan)
    assert config==requested
    scratch=_official_validate(requested,tmp_path/'scratch-input/train_config.json',monkeypatch)
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',scratch)
    # Seed an already-normalized valid checkpoint so this test independently
    # reaches the Resume path even before the separate null/default bug is fixed.
    seal_checkpoint(checkpoint,dataset=training_data,config=scratch.to_dict(),recipe_sha256='2'*64)
    new=copy.deepcopy(scratch.to_dict());new.update(resume=True,steps=4,output_dir=str(tmp_path/'resumed'))
    resume_dir=tmp_path/'resume-request';resume_dir.mkdir()
    plan=_plan(resume_dir,new,mode='resume',checkpoint=checkpoint)
    args,raw=training_command(plan)
    frozen=freeze_inputs(plan,args,raw)
    config_path=Path(next(arg.split('=',1)[1]for arg in frozen if arg.startswith('--config_path=')))
    assert config_path.is_relative_to(tmp_path)and config_path!=checkpoint/'pretrained_model/train_config.json'
    overrides=[arg for arg in frozen if arg.startswith(('--resume=','--output_dir=','--steps='))]
    source=json.loads(config_path.read_text())
    resolved=_official_validate(source,config_path,monkeypatch,overrides=overrides)
    assert resolved.policy.pretrained_path==config_path.parent
    assert resolved.output_dir==plan.output_path and resolved.steps==4 and resolved.resume
    out=_tiny_checkpoint(tmp_path/'resumed/checkpoints/000004',resolved,step=4)
    result=seal_checkpoint(out,dataset=training_data,config=raw,recipe_sha256='3'*64)
    assert result['step']==4 and result['complete']is True
    assert checkpoint_record(checkpoint)['step']==1


@pytest.mark.parametrize('change',['architecture','optimizer','dataset','steps'])
def test_normalization_does_not_accept_actual_saved_training_changes(tmp_path,training_data,monkeypatch,change):
    requested=_ui_config(training_data,tmp_path/'run')
    # Use the complete resolved request for negative tests so the existing
    # null bug cannot be the reason a malicious saved config is rejected.
    resolved=_official_validate(requested,tmp_path/'parsed/train_config.json',monkeypatch)
    wanted=resolved.to_dict()
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',resolved)
    path=checkpoint/'pretrained_model/train_config.json';saved=json.loads(path.read_text())
    if change=='architecture':saved['policy']['dim_model']+=8
    elif change=='optimizer':saved['optimizer']['lr']*=2
    elif change=='dataset':saved['dataset']['repo_id']='other/dataset'
    else:saved['steps']+=1
    path.write_text(json.dumps(saved))
    with pytest.raises(native.DataError):seal_checkpoint(checkpoint,dataset=training_data,config=wanted,recipe_sha256='4'*64)
    assert not(checkpoint/'workbench-checkpoint.json').exists()


@pytest.mark.parametrize('damage',['sha','incomplete'])
def test_finite_checkpoint_integrity_guards_survive_config_resolution(tmp_path,training_data,monkeypatch,damage):
    requested=_ui_config(training_data,tmp_path/'run')
    resolved=_official_validate(requested,tmp_path/'parsed/train_config.json',monkeypatch)
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',resolved)
    wanted=resolved.to_dict()
    if damage=='incomplete':
        (checkpoint/'training_state/rng_state.safetensors').unlink()
        with pytest.raises(native.DataError):seal_checkpoint(checkpoint,dataset=training_data,config=wanted,recipe_sha256='5'*64)
        assert not(checkpoint/'workbench-checkpoint.json').exists()
    else:
        seal_checkpoint(checkpoint,dataset=training_data,config=wanted,recipe_sha256='6'*64)
        path=checkpoint/'pretrained_model/model.safetensors';path.write_bytes(path.read_bytes()+b'tamper')
        with pytest.raises(native.DataError,match='changed/missing'):checkpoint_record(checkpoint)


@pytest.mark.parametrize('change',['architecture','optimizer','seed','batch','dataset','path'])
def test_resume_rejects_real_semantic_changes_before_freezing(tmp_path,training_data,monkeypatch,change):
    requested=_ui_config(training_data,tmp_path/'scratch')
    resolved=_official_validate(requested,tmp_path/'input/train_config.json',monkeypatch)
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',resolved)
    seal_checkpoint(checkpoint,dataset=training_data,config=requested,recipe_sha256='7'*64)
    new=copy.deepcopy(requested);new.update(resume=True,steps=4,output_dir=str(tmp_path/'resumed'))
    if change=='architecture':new['policy']['dim_model']+=8
    elif change=='optimizer':new['optimizer']=resolved.to_dict()['optimizer'];new['optimizer']['lr']*=2
    elif change=='seed':new['seed']+=1
    elif change=='batch':new['batch_size']+=1
    elif change=='dataset':new['dataset']['repo_id']='other/dataset'
    else:new['policy']['pretrained_path']=str(checkpoint/'pretrained_model')+'-unowned'
    plan=_plan(tmp_path,new,mode='resume',checkpoint=checkpoint)
    with pytest.raises(native.DataError):training_command(plan)
    assert not Path(new['output_dir']).exists()
    assert not Path(new['output_dir']+'.resume-input').exists()


def test_finetune_official_defaults_and_legacy_checkpoint_read_compatibility(tmp_path,training_data,monkeypatch):
    requested=_ui_config(training_data,tmp_path/'scratch')
    scratch=_official_validate(requested,tmp_path/'input/train_config.json',monkeypatch)
    checkpoint=_tiny_checkpoint(tmp_path/'closed/000001',scratch)
    old=seal_checkpoint(checkpoint,dataset=training_data,config=requested,recipe_sha256='8'*64)
    # A real version1 record with no new optional fields remains readable.
    old.pop('resolved_config',None)
    (checkpoint/'workbench-checkpoint.json').write_text(json.dumps(old))
    assert checkpoint_record(checkpoint)==old
    new=copy.deepcopy(requested);new['output_dir']=str(tmp_path/'finetune')
    new['policy']['pretrained_path']=str(checkpoint/'pretrained_model')
    plan=_plan(tmp_path,new,mode='finetune',policy=checkpoint/'pretrained_model')
    argv,raw=training_command(plan)
    assert raw==new and '--resume=true'not in argv
    resolved=_official_validate(raw,tmp_path/'finetune-input/train_config.json',monkeypatch)
    sealed=_tiny_checkpoint(tmp_path/'finetune/checkpoints/000001',resolved)
    assert seal_checkpoint(sealed,dataset=training_data,config=raw,recipe_sha256='9'*64)['complete']
    # The same legacy parent can still Resume into an independent output.
    new=copy.deepcopy(requested);new.update(resume=True,steps=4,output_dir=str(tmp_path/'resume-legacy'))
    argv,_=training_command(_plan(tmp_path,new,mode='resume',checkpoint=checkpoint))
    assert '--resume=true'in argv


